export function emojiFromUsername(
  username?: string | null,
  fallbackId?: string
): string {
  const s = (username || fallbackId || '?').toString()
  let h = 0
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0
  if (!ALL_GROUP_EMOJIS.length) return '🎭'
  return ALL_GROUP_EMOJIS[h % ALL_GROUP_EMOJIS.length]
}