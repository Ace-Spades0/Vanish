/** Only real emoji characters (filters accidental English words) */
function isEmojiLike(s: string) {
  if (!s || s.length > 12) return false
  if (/[a-zA-Z_]{2,}/.test(s)) return false
  return true
}

export const ALL_GROUP_EMOJIS: string[] = Array.from(
  new Set(
    EMOJI_CATEGORIES.flatMap((c) => c.icons).filter(isEmojiLike)
  )
)

export function emojiFromUsername(
  username?: string | null,
  fallbackId?: string
): string {
  const s = (username || fallbackId || '?').toString()
  let h = 0
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0
  if (!ALL_GROUP_EMOJIS.length) return '🎭'
  return ALL_GROUP_EMOJIS[h % ALL_GROUP_EMOJIS.length]
}